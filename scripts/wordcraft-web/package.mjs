import { createHash } from 'node:crypto';
import { readFile, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const [source, destination] = process.argv.slice(2);
if (!source || !destination)
  throw new Error('Usage: package.mjs <bindgen-output> <public/app>');
const hash = (data) =>
  createHash('sha256').update(data).digest('hex').slice(0, 16);
const binary = await readFile(join(source, 'wordcraft-web_bg.wasm'));
const compressed = gzipSync(binary, { level: 9 });
if (compressed.length >= 25 * 1024 * 1024) {
  throw new Error(
    'Editor exceeds the Cloudflare 25 MiB asset limit; run wasm-opt before packaging.'
  );
}
const wasm = `wordcraft-web-${hash(compressed)}_bg.wasm.gz`;
const glue = (
  await readFile(join(source, 'wordcraft-web.js'), 'utf8')
).replaceAll('wordcraft-web_bg.wasm', wasm);
const javascript = `wordcraft-web-${hash(glue)}.js`;
await writeFile(join(destination, wasm), compressed);
await writeFile(join(destination, javascript), glue);
const manifest =
  `// Generated by scripts/update-wordcraft-web.sh.\n` +
  `export const javascript = './${javascript}';\nexport const wasm = './${wasm}';\n` +
  `export const downloadBytes = ${compressed.length};\n` +
  `export const multilingualFonts = true;\n`;
await writeFile(join(destination, 'build.mjs.tmp'), manifest);
await rename(
  join(destination, 'build.mjs.tmp'),
  join(destination, 'build.mjs')
);
console.log({
  javascript,
  wasm,
  downloadMiB: (compressed.length / 1048576).toFixed(1),
});
