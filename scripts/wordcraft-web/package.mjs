import { createHash } from 'node:crypto';
import { cp, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const [source, destination, version] = process.argv.slice(2);
if (!source || !destination)
  throw new Error(
    'Usage: package.mjs <release-directory> <public/app> <version>'
  );
const hash = (data) =>
  createHash('sha256').update(data).digest('hex').slice(0, 16);
const files = await readdir(source);
const binaries = files.filter((name) =>
  /^wordcraft-web.*_bg\.wasm$/.test(name)
);
const scripts = files.filter((name) => /^wordcraft-web.*\.js$/.test(name));
if (
  binaries.length !== 1 ||
  scripts.length !== 1 ||
  !/^\d+\.\d+\.\d+$/.test(version ?? '')
)
  throw new Error(
    'Expected one release WASM, one binding module and a release version.'
  );
const binary = await readFile(join(source, binaries[0]));
const compressed = gzipSync(binary, { level: 9 });
if (compressed.length >= 25 * 1024 * 1024) {
  throw new Error(
    'Editor exceeds the Cloudflare 25 MiB asset limit; run wasm-opt before packaging.'
  );
}
const wasm = `wordcraft-web-${hash(compressed)}_bg.wasm.gz`;
const glue = (await readFile(join(source, scripts[0]), 'utf8'))
  .replaceAll(binaries[0], wasm)
  .replaceAll('wordcraft-web_bg.wasm', wasm);
const javascript = `wordcraft-web-${hash(glue)}.js`;
await writeFile(join(destination, wasm), compressed);
await writeFile(join(destination, javascript), glue);
await cp(join(source, 'snippets'), join(destination, 'snippets'), {
  recursive: true,
});
const manifest =
  `// Generated by scripts/update-wordcraft-web.sh.\n` +
  `export const javascript = './${javascript}';\nexport const wasm = './${wasm}';\n` +
  `export const downloadBytes = ${compressed.length};\n` +
  `export const multilingualFonts = true;\n`;
await writeFile(
  join(destination, 'build.mjs.tmp'),
  manifest + `export const version = '${version}';\n`
);
await rename(
  join(destination, 'build.mjs.tmp'),
  join(destination, 'build.mjs')
);
console.log({
  javascript,
  wasm,
  downloadMiB: (compressed.length / 1048576).toFixed(1),
});
